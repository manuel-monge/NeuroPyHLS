"""Generate docs result pages from the summaries in ``results/``. Run before ``zensical build``.

Each ``results/<kernel>.json`` holds one verification summary, e.g.
``{"kernel": "bandpass", "backend": "bambu", "snr_db": 74.2, "luts": 812}``.
They are collected into a table in ``docs/results/summary.md``.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
OUT = ROOT / "docs" / "results" / "summary.md"


def main() -> None:
    rows = [json.loads(p.read_text()) for p in sorted(RESULTS.glob("*.json"))]
    lines = [
        "# Results summary",
        "",
        "Generated by `scripts/gen_docs.py` from `results/*.json`.",
        "",
    ]
    if not rows:
        lines.append("No results yet. The first kernel is bandpass filter + threshold detection.")
    else:
        cols = list(dict.fromkeys(k for r in rows for k in r))
        lines += ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        lines += ["| " + " | ".join(str(r.get(c, "")) for c in cols) + " |" for r in rows]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} results)")


if __name__ == "__main__":
    main()
